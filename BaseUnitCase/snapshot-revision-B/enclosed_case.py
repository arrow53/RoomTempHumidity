def csg_mesh(add,sub):
    axes=[sorted(set(b[i] for b in add+sub for i in (a,a+3))) for a in range(3)]
    occupied=set()
    def inside(p,b): return all(b[a]<p[a]<b[a+3] for a in range(3))
    for i in range(len(axes[0])-1):
      for j in range(len(axes[1])-1):
       for k in range(len(axes[2])-1):
        p=[(axes[a][v]+axes[a][v+1])/2 for a,v in enumerate((i,j,k))]
        if any(inside(p,b) for b in add) and not any(inside(p,b) for b in sub): occupied.add((i,j,k))
    vertices=[]; index={}; triangles=[]
    def vertex(p):
      if p not in index: index[p]=len(vertices); vertices.append(p)
      return index[p]
    for ijk in sorted(occupied):
      for a in range(3):
       for sign in (-1,1):
        neighbor=list(ijk);neighbor[a]+=sign
        if tuple(neighbor) in occupied: continue
        b=(a+1)%3;c=(a+2)%3
        corners=[]
        for u,v in [(0,0),(1,0),(1,1),(0,1)]:
          q=list(ijk);q[a]+=sign==1;q[b]+=u;q[c]+=v
          corners.append(vertex(tuple(axes[t][q[t]] for t in range(3))))
        if sign<0: corners.reverse()
        triangles += [(corners[0],corners[1],corners[2]),(corners[0],corners[2],corners[3])]
    return vertices,triangles

def cross(a,b,c):return (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])
def polygon_mesh(poly,thick):
    # Ear clipping for a simple counterclockwise polygon; includes open-top slot.
    remaining=list(range(len(poly)));caps=[]
    while len(remaining)>3:
      for j,b in enumerate(remaining):
        a=remaining[j-1];c=remaining[(j+1)%len(remaining)]
        if cross(poly[a],poly[b],poly[c])<=1e-9:continue
        if any(all(cross(poly[u],poly[v],poly[p])>=-1e-9 for u,v in [(a,b),(b,c),(c,a)]) for p in remaining if p not in (a,b,c)):continue
        caps.append((a,b,c));remaining.remove(b);break
      else:raise ValueError('Invalid foot polygon')
    caps.append(tuple(remaining));n=len(poly)
    vertices=[(x,y,z) for z in (0,thick) for x,y in poly]
    triangles=[(c,b,a) for a,b,c in caps]+[(a+n,b+n,c+n) for a,b,c in caps]
    for a in range(n):
      b=(a+1)%n;triangles += [(a,b,b+n),(a,b+n,a+n)]
    return vertices,triangles

def write_mesh(name,mesh):
    vs,ts=mesh;edges=Counter(tuple(sorted((a,b))) for t in ts for a,b in zip(t,(t[1],t[2],t[0])))
    directed=Counter((a,b) for t in ts for a,b in zip(t,(t[1],t[2],t[0])))
    assert all(n==2 for n in edges.values()),name+' nonmanifold'
    assert all(directed[(a,b)]==directed[(b,a)] for a,b in edges),name+' inconsistent winding'
    vol=0
    for t in ts:
      a,b,c=[vs[i] for i in t]
      vol+=sum(a[i]*(b[(i+1)%3]*c[(i+2)%3]-b[(i+2)%3]*c[(i+1)%3]) for i in range(3))/6
    assert vol>0,name+' inverted'
    with (OUT/(name+'.stl')).open('wb') as f:
      f.write(b'Prototype mm; see ASSEMBLY.txt'.ljust(80,b' '));f.write(struct.pack('<I',len(ts)))
      for t in ts:f.write(struct.pack('<12fH',0,0,0,*[v for i in t for v in vs[i]],0))
    return dict(triangles=len(ts),bounds_mm=[[min(v[a] for v in vs),max(v[a] for v in vs)] for a in range(3)],volume_mm3=round(vol,2),closed_edges=True,consistent_winding=True)

